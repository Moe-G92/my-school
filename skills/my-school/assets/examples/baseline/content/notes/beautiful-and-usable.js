  body: `In 1995 two researchers at Hitachi, Masaaki Kurosu and Kaori Kashimura, showed people a series of cash machine screen layouts and asked them to rate how attractive each one was and how easy it looked to use. The two ratings moved together. Layouts people found beautiful, they also expected to be easier. Noam Tractinsky repeated the study in Israel two years later and found an even stronger link.

This is the aesthetic-usability effect, and mostly it is good news. Attractive interfaces earn patience. People try harder, forgive small glitches and give the product the benefit of the doubt. Visual care is part of usability, and anyone who treats it as decoration is leaving that goodwill on the table.

## The trap

The same effect works against you when you test. Put a polished prototype in front of five people and they will often say they love it while they struggle to finish the task. The beauty colours their judgement of how it went. If you only listen to what they say, you will ship problems that a plainer prototype would have exposed.

The goodwill also wears off. A handsome interface helps on the first day, when people are deciding whether to trust you. A few months later they are using it daily, and the extra click on every task has become the main thing they feel. Beauty buys patience, and the patience runs out.

## Measure them separately

The answer is to care about both and to measure them apart. Make things beautiful, because it helps. Then judge usability by what people do: whether they finished the task, how long it took, where they hesitated. Treat what they say about the look as a separate signal, and a less reliable one.

AI tools make this trap easier to fall into, because they produce polished screens instantly. A generated interface can look finished long before anyone has checked whether it works, and its polish will charm you as much as anyone else.

> In every usability test, write down what people did before you write down what they said. Count a task as passed only if they completed it without help, however much they praised the screen.

Keep the praise too. It tells you the visual work is landing. It just cannot tell you whether the product works.`,
