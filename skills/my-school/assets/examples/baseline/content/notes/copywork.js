  body: `Benjamin Franklin taught himself to write by copying. In his autobiography he describes taking essays from The Spectator, a London paper he admired, jotting short notes on each sentence, putting the original away, and a few days later rewriting the essay from his notes alone. Then he compared his version with the original and studied every place where his was worse.

Painters have done the same for centuries. The Louvre still runs a programme for copyists who set up easels in its galleries. Interface design can be learned the same way.

## What copying teaches

When you rebuild a well-made screen from scratch, say a checkout page or an issue view in a tool you admire, you stop seeing it as a whole and start seeing it as a stack of decisions. You might find that the space above each heading is larger than the space below it. You might find there are only two font weights on the page, or that the grey you took for one grey is three.

None of this is visible when you simply look. All of it becomes obvious when you try to reproduce the screen and your version looks slightly wrong. That gap between your copy and the original is the lesson, because each difference is a decision the original designer made that you had not yet learned to see.

## When to stop

Copying has limits. It shows you how something was made, which is a different thing from why. A layout that suits a project management tool may be wrong for a recipe site, and copying it whole carries over choices that only made sense in their first home.

So treat copies as exercises and never ship them. Copy to learn, then close the original and design your own screen for your own problem, keeping the reasons and leaving the pixels behind.

Stop copying a particular source once you can predict its decisions before you look. At that point it has taught you what it can, and you need a new source or more of your own work.

> Once a week, rebuild one screen you admire from a screenshot, without inspecting its code. Then lay your version over the original and write down five differences. Those notes are worth more than an hour of browsing.

The notes also make excellent prompts. Five precise observations about spacing and weight will steer an AI tool far better than the name of the product you admire.`,
