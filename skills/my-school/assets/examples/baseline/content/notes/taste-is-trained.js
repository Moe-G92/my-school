  body: `People talk about taste as something you either have or lack. Designers who have it rarely describe it that way. They describe years of looking at work, noticing why some of it holds up, and slowly getting quicker at seeing it.

The radio presenter Ira Glass gave a well-known account of this that applies to any creative work. In paraphrase, you get into the work because you have good taste. For the first few years, what you make falls short of that taste, and you can tell, which is painful. The way through is volume, which means making things until your work catches up with what you can recognise.

## Noticing, then naming

Two abilities are being trained. The first is noticing. You see that a heading sits a little too close to the paragraph below it, that two greys are almost but not quite the same, that a button says one thing and the page title another. The second is naming, which means being able to say why something works in words you could hand to someone else.

Noticing without naming leaves you with a vague feeling that something is off. Naming without noticing gives you rules you apply in the wrong places. Both improve fastest through comparison. One good screen on its own teaches you little. Put two versions side by side, the same pricing page from two companies for example, and every decision jumps out, because each difference is a choice someone made.

## Taste is specific

Good taste in a banking app and good taste in a festival poster are different things. Part of a trained eye is knowing what fits a context: dense and calm for a tool used all day, generous and expressive for a page someone sees once.

That also means taste is learnable in pieces. You can get good at forms before you get good at illustration, and good at dashboards before landing pages. Pick the kind of screen you build most and train on that first.

> Once a day, save one screenshot of an interface that works well and write one sentence on why. Be specific. "The price is the darkest thing on the card" teaches you more than "clean".

After a few months you will have a few hundred examples and, more usefully, a few hundred sentences. That collection is the start of a trained eye. It is also the best thing to show an AI tool when you need it to understand what you mean.`,
