  body: `Most people have pulled a door that needed pushing and felt a little foolish. Don Norman's argument, in The Design of Everyday Things, is that the foolishness belongs to the door. A flat plate where your hand goes says push. A vertical bar says pull. When a door has a bar on its push side, it is telling you something false, and the paper sign taped above it saying PUSH is the designer's confession.

Doors like this are now called Norman doors. The useful word in his account is signifier, meaning a cue you can perceive that shows what you can do and where. The door affords pushing. The handle signals pulling. People believe the handle.

## Screens are full of doors

Every interactive element on a screen is a small door. A grey rectangle might be a button or a decoration. Blue text might be a link or a heading someone liked the colour of. An icon might open a menu, or it might do something irreversible the moment you touch it. Each time a person has to wonder, the interface has failed the way the door did, only more quietly, because nobody can tape a sign to it.

The fix is the same as for the door. Make things that act look as if they act, and make things that do not act look still. Buttons get a shape, a label and a visible change when pressed. Links look the same everywhere. Anything that looks tappable, such as a card with a shadow, either does something when tapped or loses the shadow.

## Instructions are a symptom

The most useful habit Norman gives you is to treat every instruction as evidence. A tooltip that says "click the pencil to edit" or an onboarding slide that teaches a hidden gesture marks a place where the design did not explain itself. Sometimes help text is the right answer. More often it is the sign on the door.

This gets harder to see the longer you work on something. You know where everything is, so nothing looks ambiguous to you. The only reliable check is a fresh pair of eyes.

> Hand your product to someone who has never seen it, give them one task, and say nothing at all. Each time you feel the urge to explain, write down what you would have said. That list is your missing signifiers.

Then fix the doors, one at a time, until the list is short.`,
