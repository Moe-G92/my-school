  body: `When you design, you are usually at your best. You sit at a large screen on fast Wi-Fi, rested, with both hands free, looking at a product you know inside out. Hardly any of your users will meet your product in those conditions.

Picture someone else. She is on a station platform, trying to buy a ticket on her phone before a train arrives in three minutes. She has a coffee in one hand and a bag on her shoulder, so she is using one thumb. The signal keeps dropping, and she slept badly. Every unnecessary field and every small button at the top of the screen is now a real obstacle, and a page waiting on a large image may not load before the doors close.

## Situational limits

Microsoft's inclusive design guidance describes a spectrum. Someone may have one arm, have an arm in a cast for a few weeks, or be holding a baby. A design that works for the first person also works for the other two. The tired, distracted, one-handed user on a bad connection is nearly everyone at some point in the day, including you.

## What changes when you design for her

Designing for her changes concrete things. Primary actions move to the lower half of the screen, within reach of a thumb. Tap targets meet the platform minimums of 44 points on iOS and 48 dp on Android, or exceed them. Forms ask for less and accept what people type in any reasonable format. Text has enough contrast to read outdoors. Pages show something useful before every image has arrived, and a dropped connection does not throw away what she typed.

Each of these is a small change. Together they decide whether she gets the ticket or watches the train leave.

Your own setup hides all of this from you, so you have to recreate her conditions on purpose. Designers rarely do, because the desk is comfortable and the deadline is close.

> Once a week, use your own product standing up, with one thumb, on a connection throttled in your browser's developer tools, late in the evening. Write down the first three things that annoyed you, and fix one of them.

If you build with AI tools, describe her in the prompt as well. A model asked to design for a tired commuter with one free thumb makes noticeably different choices from one asked for a modern, clean design.`,
